def read_source(path, name):
    data = Path(path).read_bytes()
    if hashlib.sha256(data).hexdigest() != SOURCES[name]:
        raise SystemExit(f"{path} is not 12dicts 2020.12.07 {name} (expected SHA-256 {SOURCES[name]})")
    return data.decode("latin-1")


def common_words(full):
    """The lower-case words, not phrases, at least MIN_DICTIONARIES dictionaries list."""
    words = set()
    for line in full.splitlines():
        match = re.fullmatch(r"\s*(\d+):\s+\S+\s+\S+\s+\S+\s+\S+\s+(\S.*?)\s*", line)
        if not match:
            raise ValueError(f"Unrecognized 2of12full line: {line!r}")
        if int(match[1]) >= MIN_DICTIONARIES and WORD.fullmatch(match[2]):
            words.add(match[2])
    return words


def inflections(listing, words):
    """Each word's inflections in 2of12id: not the ones marked unusual (a
    leading hyphen), archaic (@), uncountable (~) or variant (in brackets)."""
    forms = set()
    for line in listing.splitlines():
        head, separator, rest = line.partition(":")
        # A leading hyphen marks a usage none of the twelve shows, @ an archaic
        # one and a plus a neologism.
        match = re.fullmatch(r"([-+@]?)([a-z]+) [A-Z]\??(?: \{[^}]*\})?", head)
        if not separator or not match:
            raise ValueError(f"Unrecognized 2of12id line: {line!r}")
        if match[1] in ("-", "@") or match[2] not in words:
            continue
        rest = re.sub(r"\([^)]*\)|\{[^}]*\}", " ", rest)
        forms.update(form for form in rest.replace("|", " ").split() if WORD.fullmatch(form))
    return forms


def british(words):
    """VOCO's British spelling of any American word among them."""
    spellings = set()
    for line in SPELLING.read_text(encoding="utf-8").splitlines():
        if line.startswith("british\t"):
            _, american, spelling = line.split("\t")
            if american in words:
                spellings.add(spelling)
    return spellings


def render(full, listing):
    words = common_words(full)
    words |= inflections(listing, words)
    words |= british(words)
    words |= set(SAID)
    notice = NOTICE.format(minimum=MIN_DICTIONARIES, full_url=BASE_URL + "2of12full.txt",
                           full_sha256=SOURCES["2of12full.txt"], id_url=BASE_URL + "2of12id.txt",
                           id_sha256=SOURCES["2of12id.txt"])
    return notice + "".join(f"{word}\n" for word in sorted(words)), len(words)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("full", help="the pinned 12dicts 2020.12.07 2of12full.txt")
    parser.add_argument("listing", help="the pinned 12dicts 2020.12.07 2of12id.txt")
    parser.add_argument("--check", action="store_true", help="fail if the committed list differs")
    arguments = parser.parse_args()
    content, count = render(read_source(arguments.full, "2of12full.txt"),
                            read_source(arguments.listing, "2of12id.txt"))
    if arguments.check:
        if not LIST.is_file() or LIST.read_text(encoding="utf-8") != content:
            print(f"{LIST.relative_to(ROOT)} is stale; regenerate it from 12dicts", file=sys.stderr)
            return 1
        print(f"Everyday words match 12dicts 2020.12.07: {count} words")
        return 0
    LIST.write_text(content, encoding="utf-8")
    print(f"Wrote {LIST.relative_to(ROOT)}: {count} words")
    return 0


if __name__ == "__main__":
    sys.exit(main())
