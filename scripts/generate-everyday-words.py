"""Generate My words' list of everyday words from 12dicts 2020.12.07.

Teaching VOCO a version of a listed word, the way it heard it, makes the
worker change that version wherever it hears it. Settings warns before
teaching one made only of everyday words, and setup prefers teaching a whole
name to teaching one word of it that people say all the time.

An everyday word is a lower-case word that at least ten of the twelve
dictionaries behind 12dicts list (2of12full.txt), with its inflections from
2of12id.txt and the British spelling VOCO writes for any of them, and "I" and
the contractions people say most. The files aren't in the repository; fetch the
pinned ones, then regenerate or check the list:

  curl -fLo 2of12full.txt https://raw.githubusercontent.com/en-wl/wordlist/rel-2020.12.07/alt12dicts/2of12full.txt
  curl -fLo 2of12id.txt https://raw.githubusercontent.com/en-wl/wordlist/rel-2020.12.07/alt12dicts/2of12id.txt
  python3 scripts/generate-everyday-words.py 2of12full.txt 2of12id.txt
  python3 scripts/generate-everyday-words.py --check 2of12full.txt 2of12id.txt
"""
