#!/usr/bin/env python3
"""Generate the speech worker's spelling table from VarCon 2020.12.07.

The table keeps a form only when VarCon prefers it in one variety, doesn't
list it at all in the other, and gives it one spelling there across every
meaning: "color" becomes "colour", but "program", "check" and "practice"
stay, because British English uses them too. VarCon isn't in the repository;
fetch the pinned file, then regenerate or check the table:

  curl -fLo varcon.txt https://raw.githubusercontent.com/en-wl/wordlist/rel-2020.12.07/varcon/varcon.txt
  python3 scripts/generate-spelling-table.py varcon.txt
  python3 scripts/generate-spelling-table.py --check varcon.txt
"""
import argparse
import collections
