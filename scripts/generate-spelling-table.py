def read_source(path):
    data = Path(path).read_bytes()
    if hashlib.sha256(data).hexdigest() != SOURCE_SHA256:
        raise SystemExit(f"{path} is not VarCon 2020.12.07 (expected SHA-256 {SOURCE_SHA256})")
    # VarCon is Latin-1; its few non-ASCII words are all in the "other" category.
    return data.decode("latin-1")


def parse(text):
    """Clusters of lines; each line lists (word, {category: variant mark})."""
    clusters = []
    for raw in text.splitlines():
        if raw.startswith("##") or not raw.strip():
            continue
        if raw.startswith("# "):
            header = re.fullmatch(r"# (.+?) (<verified> )?\(level (\d+)\)", raw)
            if not header:
                raise ValueError(f"Unrecognized VarCon cluster: {raw}")
            clusters.append({"verified": bool(header[2]), "level": int(header[3]), "lines": []})
            continue
        # Usage notes follow " | " and comments follow "#"; neither changes spelling.
        body = raw.split("#", 1)[0].split(" | ", 1)[0].strip()
        line = []
        for entry in body.split(" / "):
            tags, separator, word = entry.partition(": ")
            if not separator or not word.strip():
                raise ValueError(f"Unrecognized VarCon entry: {raw}")
            categories = {}
            for tag in tags.split():
                if tag.isdigit():  # a column number
                    continue
                match = TAG.fullmatch(tag)
                if not match:
                    raise ValueError(f"Unrecognized VarCon tag {tag!r}: {raw}")
                categories[match[1]] = match[2]
            line.append((word.strip(), categories))
        clusters[-1]["lines"].append(line)
    return clusters


def regular(american, british):
    def canonical(word):
        for variant, common in REGULAR:
            word = word.replace(variant, common)
        return word
    return canonical(american) == canonical(british)


def build(clusters, source, target):
    """Forms preferred in `source`, unlisted in `target`, with one target spelling."""
    lines = collections.defaultdict(list)
    kept = set()
    for cluster in clusters:
        words = {word for line in cluster["lines"] for word, _ in line}
        # A kept word keeps its whole cluster: plurals, possessives and tenses.
        if words & KEEP_AS_SAID:
            kept |= words
        if cluster["level"] > MAX_LEVEL:
            continue
        for line in cluster["lines"]:
            for word, categories in line:
                lines[word].append((line, categories, cluster["verified"]))
    table = {}
    for word, occurrences in lines.items():
        if word != word.lower() or word in kept:
            continue
        spellings = set()
        for line, categories, verified in occurrences:
            preferred = [other for other, tags in line if tags.get(target) == ""]
            if target in categories or categories.get(source) != "" or len(preferred) != 1:
                break
            spellings.add((preferred[0], verified))
        else:
            if len({spelling for spelling, _ in spellings}) != 1:
                continue
            (spelling, verified), = spellings
            american, british = (word, spelling) if source == "A" else (spelling, word)
            if (spelling == spelling.lower() and spelling not in kept
                    and (verified or regular(american, british))):
                table[word] = spelling
    return table


def render(clusters):
    rows = []
    counts = {}
    for mode, (source, target) in MODES.items():
        table = build(clusters, source, target)
        counts[mode] = len(table)
        rows += [f"{mode}\t{word}\t{table[word]}\n" for word in sorted(table)]
    return NOTICE.format(url=SOURCE_URL, sha256=SOURCE_SHA256) + "".join(rows), counts


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("source", help="the pinned VarCon 2020.12.07 varcon.txt")
    parser.add_argument("--check", action="store_true", help="fail if the committed table differs")
    arguments = parser.parse_args()
    content, counts = render(parse(read_source(arguments.source)))
    summary = ", ".join(f"{mode} {count}" for mode, count in counts.items())
    if arguments.check:
        if not TABLE.is_file() or TABLE.read_text(encoding="utf-8") != content:
            print(f"{TABLE.relative_to(ROOT)} is stale; regenerate it from VarCon", file=sys.stderr)
            return 1
        print(f"Spelling table matches VarCon 2020.12.07: {summary}")
        return 0
    TABLE.write_text(content, encoding="utf-8")
    print(f"Wrote {TABLE.relative_to(ROOT)}: {summary}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
