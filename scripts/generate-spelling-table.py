ROOT = Path(__file__).resolve().parent.parent
TABLE = ROOT / "runtime/speech/spelling-varcon.tsv"
SOURCE_URL = "https://raw.githubusercontent.com/en-wl/wordlist/rel-2020.12.07/varcon/varcon.txt"
SOURCE_SHA256 = "340858b990255ec409adcf7faaf2b992aa2a76a16f30b4b9e2663863191dba33"
# SCOWL levels above 60 hold rare and junk forms: level 80 turns "Ernest"
# into "Renest".
MAX_LEVEL = 60
MODES = {"british": ("A", "B"), "american": ("B", "A")}
TAG = re.compile(r"([ABZCD_])([.vV\-x]?)")
# Pairs VarCon calls spelling variants that a listener hears apart, so the
# recognizer already wrote what was said, and forms whose meaning differs in
# use. Each stays as recognized in both directions.
KEEP_AS_SAID = {
    "airplane", "aeroplane", "airfoil", "aerofoil",  # different first syllable
    "aluminum", "aluminium",
    "math", "maths",
    "mom", "mum",  # "mums" are flowers in American English too
    "specialty", "speciality",
    "tidbit", "titbit",
    "behoove", "behove",
    "furor", "furore",
    "flutist", "flautist",
    "learned", "learnt", "unlearnt", "spoilt",
    "ass", "arse", "asshole", "arsehole",
    "fagot", "faggot",
    "peddler", "pedlar",  # British keeps "peddler" for drugs
    "whiskey", "whisky",  # Irish whiskey keeps its "e"
    "groin",  # "groins" of the body aren't "groynes"
    "reprized",  # American English writes "reprised" too
}
# Unverified clusters keep only -our, -ise and -ll- pairs; their other pairs
# include junk such as "perv" to "prev" and "mantes" to "mantoes".
REGULAR = (("our", "or"), ("is", "iz"), ("ll", "l"))
